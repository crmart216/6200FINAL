from __future__ import annotations
from dataclasses import dataclass, field
from cryptography.hazmat.primitives.asymmetric.x25519 import X25519PrivateKey
from .ratchet_tree import RatchetTree

@dataclass(eq=False)
class GroupState:
    """Hold one member's local view of a group at its current epoch.

    The group ID and title identify the conversation. The member's leaf
    index identifies their position in the public ratchet tree. The private
    tree key map contains only the keys this member holds, indexed by tree
    node index. Epoch secrets can be absent during initialization. The
    sender-ratchet map tracks message progress by sender leaf index.

    Documentation generated by GPT-6.2 Sol. 
    """
    
    group_id: str
    title: str
    epoch: int
    own_leaf_index: int
    ratchet_tree: RatchetTree

    # Indexed by tree node index. The public tree stores public keys. 
    # Public Key Tree stores every user and node in the group chat with their public key
    # This is used to match the private keys the user knows to a public key for a node in the tree.

    _private_tree_keys: dict[int, X25519PrivateKey] = field(default_factory=dict, repr=False)

    # Stores secrets for the current epoch. This is used to derive the secrets for the next epoch.
    _epoch_secrets: EpochSecrets | None = field(default=None, repr=False)

    # Each dictionary key is a sender's leaf index
    _sender_ratchets: dict[int, SenderRatchet] = field(default_factory=dict, repr=False)

    def private_tree_keys_snapshot(self) -> dict[int, X25519PrivateKey]:
        return self._private_tree_keys.copy()

    def require_init_secret(self) -> bytes:
        if self._epoch_secrets is None:
            raise ValueError("Current epoch secrets are missing.")
        return self._epoch_secrets.init_secret

    
@dataclass(frozen=True, eq=False, repr=False)
class EpochSecrets:
    """Hold the key material for a single group epoch.

    The initialization secret feeds the next epoch's key schedule. The
    encryption secret seeds message-key ratchets, and the sender-data
    secret protects sender metadata. The confirmation and membership
    keys are for their respective authentication tags. The instance is
    frozen and its generated repr is disabled.

    Documentation generated by GPT-6.2 Sol. 
    """
    init_secret: bytes
    encryption_secret: bytes
    sender_data_secret: bytes
    confirmation_key: bytes
    membership_key: bytes

@dataclass(eq=False)
class SenderRatchet:
    """Track one sender's application-message key chain for an epoch.

    The chain secret is the current input for deriving message key
    material. The next generation counts which position in the chain
    will be used next and starts at zero. Each GroupState stores these
    objects by sender leaf index. The repr omits the chain secret.

    Documentation generated by GPT-6.2 Sol. 
    """
    chain_secret: bytes = field(repr=False)
    next_generation: int = 0

from __future__ import annotations
from collections.abc import Iterator
from dataclasses import dataclass
from ..key_models.key_package import PublicKeyPackage

@dataclass
class RatchetTree:
    """Represent the group's public keys in a linked binary tree.

    The root is absent in an empty tree. The leaf list is used to look up
    members by zero-based leaf index. A leaf's tree node index is twice its
    leaf index, while internal nodes use odd node indices. Insertion is
    designed to attach a leaf at the right edge and introduce a parent
    where needed. Tree printing follows child links from the root.

    Documentation generated by GPT-6.2 Sol. 
    """
    def __init__(self):
        """Initialize an empty tree with no root and an empty leaf list. Documentation generated by GPT-6.2 Sol. """
        self.root: TreeNode | None = None
        self._leaves: list[TreeNode] = []
    
    def insert_member(self, package: PublicKeyPackage) -> int:
        """Add a member's public key package to the tree and return its leaf index. Documentation generated by GPT-6.2 Sol. """
        leaf_index = len(self._leaves)
        leaf = TreeNode(
            node_index=2 * leaf_index, 
            public_key=package.leaf_public_key,
        )
        if self.root is None:
            self.root = leaf
            self._leaves.append(leaf)
            return leaf_index
        
        subtree_size = leaf_index & -leaf_index
        leftmost_node_index = 2 * (leaf_index - subtree_size)
        subtree = self._leaves[-1]

        while (subtree.parent is not None and subtree.parent.node_index >= leftmost_node_index):
            subtree = subtree.parent
        
        previous_parent = subtree.parent
        new_parent = TreeNode(
            node_index = leaf.node_index - 1,
            public_key=b"",
            parent=previous_parent,
            left=subtree,
            right=leaf,
        )

        if previous_parent is None:
            self.root = new_parent
        else:
            previous_parent.right = new_parent

        subtree.parent = new_parent
        leaf.parent = new_parent
        self._leaves.append(leaf)
        return leaf_index

    def get_leaf(self, leaf_index: int) -> TreeNode:
        """Return the leaf at the given index or raise IndexError for an invalid index. Documentation generated by GPT-6.2 Sol. """
        if not 0 <= leaf_index < len(self._leaves):
            raise IndexError(f"Leaf index {leaf_index} is out of bounds.")
        return self._leaves[leaf_index]
        
    def print_tree(self) -> None:
        """Print the tree's hierarchy, node indices, and public keys. Documentation generated by GPT-6.2 Sol. """
        
        if self.root is None:
            print("Ratchet tree is empty.")
            return

        def print_node(node: TreeNode, label: str, depth: int) -> None:
            """Print a node at the given indentation and recursively print its children. Documentation generated by GPT-6.2 Sol. """
            indent = "    " * depth
            details = f"node={node.node_index}"
            if node.is_leaf():
                details += f", leaf={node.node_index // 2}"

            public_key = node.public_key.hex() if node.public_key else "(unset)"
            print(f"{indent}{label} [{details}] public_key={public_key}")

            if node.left is not None:
                print_node(node.left, "Left", depth + 1)
            if node.right is not None:
                print_node(node.right, "Right", depth + 1)

        print_node(self.root, "Root", 0)
    
    def iter_leaves(self) -> Iterator[TreeNode]:
        """Iterate over leaves in leaf-index order."""
        return iter(self._leaves)

@dataclass(eq=False)
class TreeNode:
    """Represent a leaf or an internal node of the public ratchet tree.

    The node index identifies the tree position. The public key is stored
    as bytes, with empty bytes used for an internal node whose public key
    has yet to be assigned. The parent, left, and right fields are links to
    neighboring nodes. The leaf test checks whether both child links are None.

    Documentation generated by GPT-6.2 Sol. 
    """
    node_index: int
    public_key: bytes
    parent: TreeNode | None = None
    left: TreeNode | None = None
    right: TreeNode | None = None

    def is_leaf(self) -> bool:
        """Return whether both child references are None. Documentation generated by GPT-6.2 Sol. """
        return self.left is None and self.right is None 
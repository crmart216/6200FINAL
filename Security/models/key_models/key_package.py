from dataclasses import dataclass, field

from cryptography.hazmat.primitives.asymmetric.x25519 import X25519PrivateKey

# Pass the encoded credential bytes until the Credential model is implemented.
type Credential = bytes


@dataclass(frozen=True)
class PublicKeyPackage:
    """Describe the public identity and keys used to invite a participant.

    The package ID identifies the matching local private package. The
    credential is supplied as encoded bytes. The initialization public key
    is for protecting the Welcome secrets, the leaf public key is for the
    ratchet tree, and the signing public key is for checking the signature.
    The signature covers the bytes returned by serialize_unsigned.

    Documentation generated by GPT-6.2 Sol. 
    """

    package_id: str
    credential: Credential
    init_public_key: bytes
    leaf_public_key: bytes
    signing_public_key: bytes
    signature: bytes = b""  # Create the signed copy with dataclasses.replace().

    def serialize_unsigned(self) -> bytes:
        """Return the unsigned fields as length-prefixed bytes for signing or verification. Documentation generated by GPT-6.2 Sol. """
        fields = (
            self.package_id.encode("utf-8"),
            self.credential,
            self.init_public_key,
            self.leaf_public_key,
            self.signing_public_key,
        )

        # Each field starts with its length as a 4-byte big-endian integer.
        return b"6200 KeyPackage v1\x00" + b"".join(
            len(value).to_bytes(4, "big") + value for value in fields
        )


@dataclass(frozen=True, eq=False)
class PrivateKeyPackage:
    """Keep the private keys that correspond to a public key package.

    The package ID associates these keys with the published package and an
    incoming Welcome. The X25519 initialization key is for opening the
    Welcome secrets, and the X25519 leaf key is for the member's ratchet-tree
    leaf after joining. Both key fields are omitted from the object repr.

    Documentation generated by GPT-6.2 Sol. 
    """

    package_id: str
    _init_private_key: X25519PrivateKey = field(repr=False)
    _leaf_private_key: X25519PrivateKey = field(repr=False)
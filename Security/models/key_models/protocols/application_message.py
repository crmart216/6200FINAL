from dataclasses import dataclass


@dataclass(frozen=True)
class ApplicationMessage:
    """Carry an encrypted chat message for a specific group and epoch.

    The group ID and epoch let a recipient select the corresponding group
    state. The encrypted sender data carries metadata such as the sender's
    leaf index and message generation. The ciphertext carries the
    protected application payload. Message services handle encryption
    and decryption using this immutable container.

    Documentation generated by GPT-6.2 Sol. 
    """

    group_id: str
    epoch: int
    encrypted_sender_data: bytes 
    ciphertext: bytes             
from __future__ import annotations

from dataclasses import dataclass
from .proposal import Proposal, UpdatePath

@dataclass
class Commit:
    """Carry the data members process to advance the group epoch.

    The group ID and epoch identify the starting group state, and the
    sender leaf index identifies the committer. The proposal list records
    the changes to apply. The update path carries the new public keys and
    encrypted path secrets. The confirmation tag lets members check that
    they derived the expected state for the new epoch.

    Documentation generated by GPT-6.2 Sol. 
    """

    group_id: str
    epoch: int
    sender_leaf_index: int
    proposals: list[Proposal]
    update_path: UpdatePath
    confirmation_tag: bytes

@dataclass
class SignedCommit(Commit):
    signature: bytes
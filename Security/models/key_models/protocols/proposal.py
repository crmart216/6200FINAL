from __future__ import annotations
from dataclasses import dataclass
from ..key_package import PublicKeyPackage

@dataclass
class Proposal:
    """Describe one Add or Remove at a specific group epoch."""

    group_id: str
    epoch: int
    sender_leaf_index: int
    action: str
    invitee: PublicKeyPackage | None = None
    target_leaf_index: int | None = None

    def __post_init__(self) -> None:
        _ = self.require_payload()

    def require_payload(self) -> PublicKeyPackage | int:
        """Return the payload for this action or reject an invalid proposal."""
        if self.action == "add":
            if not isinstance(self.invitee, PublicKeyPackage):
                raise ValueError("An Add proposal requires an invitee package.")
            if self.target_leaf_index is not None:
                raise ValueError("An Add proposal cannot carry a target leaf index.")
            return self.invitee

        if self.action == "remove":
            if self.invitee is not None:
                raise ValueError("A Remove proposal cannot carry an invitee package.")
            target = self.target_leaf_index
            # bool is an int subclass, but True and False are invalid indices here.
            if type(target) is not int or target < 0:
                raise ValueError("A Remove proposal requires a nonnegative leaf index.")
            return target

        raise ValueError(f"Unknown proposal action: {self.action!r}.")


@dataclass
class UpdatePath:
    """Carry the committer's public tree update inside a Commit.

    The leaf public key is the committer's new key for their own leaf.
    The node list describes updated parents in order, starting at the
    lowest updated parent and moving toward the root. Each entry carries
    the replacement public key and encrypted path secrets for its recipients.

    Documentation generated by GPT-6.2 Sol. 
    """

    leaf_public_key: bytes

    # Ordered from the committer's lowest updated parent toward the root.
    nodes: list[UpdatePathNode]


@dataclass
class UpdatePathNode:
    """Carry the replacement key material for one updated parent node.

    The node index identifies the parent whose public key is being
    replaced. The encrypted path secrets are keyed by recipient tree node
    index. A recipient index can refer to a leaf or to an internal node
    whose private key is held by the intended recipients.

    Documentation generated by GPT-6.2 Sol. 
    """

    node_index: int
    public_key: bytes

    # Maps each recipient tree node index to its encrypted path secret.
    # A recipient node can be a leaf or an internal node.
    encrypted_path_secrets: dict[int, bytes]
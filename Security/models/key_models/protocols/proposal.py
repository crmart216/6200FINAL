from __future__ import annotations
from dataclasses import dataclass
from ..key_package import PublicKeyPackage

@dataclass
class Proposal:
    """Describe a requested change to a group at a given epoch.

    The group ID and epoch identify the state to which the request applies.
    The sender leaf index identifies the proposing member. The action
    names the requested change. An Add proposal includes the invitee's
    public key package. A later Commit carries the proposals to apply.

    Documentation generated by GPT-6.2 Sol. 
    """

    group_id: str
    epoch: int
    sender_leaf_index: int
    action: str

    # An Add proposal carries the invitee's public key package.
    invitee: PublicKeyPackage | None = None


@dataclass
class UpdatePath:
    """Carry the committer's public tree update inside a Commit.

    The leaf public key is the committer's new key for their own leaf.
    The node list describes updated parents in order, starting at the
    lowest updated parent and moving toward the root. Each entry carries
    the replacement public key and encrypted path secrets for its recipients.

    Documentation generated by GPT-6.2 Sol. 
    """

    leaf_public_key: bytes

    # Ordered from the committer's lowest updated parent toward the root.
    nodes: list[UpdatePathNode]


@dataclass
class UpdatePathNode:
    """Carry the replacement key material for one updated parent node.

    The node index identifies the parent whose public key is being
    replaced. The encrypted path secrets are keyed by recipient tree node
    index. A recipient index can refer to a leaf or to an internal node
    whose private key is held by the intended recipients.

    Documentation generated by GPT-6.2 Sol. 
    """

    node_index: int
    public_key: bytes

    # Maps each recipient tree node index to its encrypted path secret.
    # A recipient node can be a leaf or an internal node.
    encrypted_path_secrets: dict[int, bytes]
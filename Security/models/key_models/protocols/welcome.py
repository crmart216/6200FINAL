from __future__ import annotations

from dataclasses import dataclass

@dataclass
class Welcome:
    """Carry the encrypted data a new member needs to join a group.

    The package ID lets the recipient find the matching private key
    package. The encrypted group secrets carry the material needed to
    derive the joining member's epoch secrets. The encrypted group info
    carries the group context needed to initialize their local state.

    Documentation generated by GPT-6.2 Sol. 
    """

    package_id: str
    encrypted_group_secrets: bytes
    encrypted_group_info: bytes
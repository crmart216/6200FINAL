from dataclasses import dataclass, field

from cryptography.hazmat.primitives.asymmetric.ed25519 import Ed25519PrivateKey

from .group_models.group_state import GroupState
from .key_models.key_package import PrivateKeyPackage


@dataclass(eq=False)
class User:
    """Store a participant's identity and local group state.

    The user ID identifies the participant, and the display name is the
    human-readable label. Each instance generates its own Ed25519 signing
    key unless an existing key is supplied. Private key packages are indexed
    by package ID so a Welcome can locate the matching keys. Local group
    states are indexed by group ID so a user can participate in several groups.

    Documentation generated by GPT-6.2 Sol. 
    """

    user_id: str
    display_name: str

    # Generate a key for a new user or pass the existing key when loading one.
    signing_key: Ed25519PrivateKey = field(
        default_factory=Ed25519PrivateKey.generate,
        repr=False,
    )

    # Indexed by package_id so an incoming Welcome can find its private keys.
    private_packages: dict[str, PrivateKeyPackage] = field(
        default_factory=dict,
        repr=False,
    )

    # Indexed by group_id. Each entry holds this user's local group state.
    groups: dict[str, GroupState] = field(
        default_factory=dict,
        repr=False,
    )